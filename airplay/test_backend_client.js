'use strict';
const assert = require('assert'), fs = require('fs'), path = require('path'), vm = require('vm'), EventEmitter = require('events');
const sockets = [], intervals = new Set(), retries = new Set();
const fakeNet = { createConnection() {
    const socket = new EventEmitter(); socket.connecting = true; socket.destroyed = false; socket.writes = []; socket.ends = 0;
    socket.setEncoding = () => {};
    socket.write = text => socket.writes.push(JSON.parse(text));
    socket.end = () => { socket.ends++; socket.destroyed = true; socket.emit('close'); };
    socket.destroy = () => { socket.destroyed = true; socket.emit('close'); };
    sockets.push(socket); return socket;
} };
const context = {
    require: name => name === 'net' ? fakeNet : require(name), module: { exports: {} },
    setInterval: fn => { intervals.add(fn); return fn; }, clearInterval: fn => intervals.delete(fn),
    setTimeout: (fn,ms) => { fn.ms=ms; retries.add(fn); return fn; }, clearTimeout: fn => retries.delete(fn),
};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../apps/pllana_airplay/backend_client.js'), 'utf8'), context);
const { BackendClient } = context.module.exports;
(async () => {
    const client = new BackendClient('/private/control.sock'); client.connect();
    const socket = sockets[0];
    assert.strictEqual(client.start('audio'), false, 'a connecting socket cannot accept a command');
    socket.connecting = false; socket.emit('connect');
    assert(client.start());
    assert.deepStrictEqual(socket.writes.pop(), { command: 'start', profile: 'auto' });
    assert(client.start('video'));
    assert.deepStrictEqual(socket.writes.pop(), { command: 'start', profile: 'video' });
    assert(client.start('audio'));
    assert.deepStrictEqual(socket.writes.pop(), { command: 'start', profile: 'audio' });
    assert.strictEqual(client.start('other'), false);
    assert.strictEqual(socket.writes.length, 0, 'invalid profile is never sent');
    socket.emit('data', '{"state":{"profile":"audio","mode":"audio","phase":"waiting","supportsVideoStop":true,"connected":true}}\n');
    assert.strictEqual(client.state.connected,true,'the backend logical session status reaches the UI');
    assert.strictEqual(client.endVideo(), false, 'video stop cannot be sent in audio-only mode');
    socket.emit('data', '{"state":{"music":{"epoch":"sender-1","controls":{"playPause":true,"next":true,"previous":true,"shuffle":true,"repeat":true},"shuffle":0,"repeat":1,"playbackState":"playing"}}}\n');
    assert(client.musicControl('next')); assert.deepStrictEqual(socket.writes.pop(), {command:'music-control',action:'next',epoch:'sender-1'});
    assert(client.musicControl('shuffle',1)); assert.deepStrictEqual(socket.writes.pop(), {command:'music-control',action:'shuffle',value:1,epoch:'sender-1'});
    assert(client.musicControl('repeat',2)); assert.deepStrictEqual(socket.writes.pop(), {command:'music-control',action:'repeat',value:2,epoch:'sender-1'});
    assert.strictEqual(client.state.music.shuffle, 0, 'sending a desired setting does not invent a confirmed sender state');
    assert.strictEqual(client.state.music.repeat, 1);
    assert.strictEqual(client.musicControl('repeat','all'), false);
    assert.strictEqual(client.musicControl('shuffle',true), false);
    assert.strictEqual(client.musicControl('/arbitrary/path'), false);
    assert.strictEqual(client.musicControl('next',1), false);
    socket.emit('data', '{"state":{"music":{"epoch":"sender-2","controls":{"next":true,"shuffle":false}}}}\n');
    assert.strictEqual(client.musicControl('shuffle',1), false);
    assert(client.musicControl('next')); assert.strictEqual(socket.writes.pop().epoch,'sender-2','commands carry the current paired sender epoch');
    socket.emit('data', '{"state":{"profile":"auto","mode":"audio"}}\n');
    assert(client.musicControl('next'), 'automatic standalone audio uses the current sender controls'); socket.writes.pop();
    socket.emit('data', '{"state":{"mode":"mirror"}}\n');
    assert.strictEqual(client.musicControl('next'), false, 'cached music capabilities cannot control mirroring');
    socket.emit('data', '{"state":{"profile":"video","mode":"hls","phase":"loading","origin":"direct","supportsVideoStop":true,"music":{"epoch":"video-sender","controls":{"next":true,"previous":true,"playPause":true},"metadata":{"title":"DACP title","artist":"Phone artist","album":"Album"}}}}\n');
    assert(client.musicControl('next'), 'a live HLS loading item can use genuine sender controls');
    assert.deepStrictEqual(socket.writes.pop(), {command:'music-control',action:'next',epoch:'video-sender'});
    assert.strictEqual(client.state.music.metadata.title,'DACP title');
    socket.emit('data', '{"state":{"phase":"mirroring","frame":{"sequence":1}}}\n');
    assert(client.musicControl('previous'), 'decoded HLS frames use the native mirroring phase');
    assert.deepStrictEqual(socket.writes.pop(), {command:'music-control',action:'previous',epoch:'video-sender'});
    for (const phase of ['waiting','audio','error','stopped']) {
        socket.emit('data', JSON.stringify({state:{mode:'hls',phase}})+'\n');
        assert.strictEqual(client.musicControl('next'),false,'a stale HLS mode cannot authorize phase '+phase);
    }
    socket.emit('data', '{"state":{"mode":"waiting","phase":"waiting","playlistPending":true,"returnMode":"waiting","connected":true}}\n');
    assert(client.musicControl('next'), 'a connected direct-video playlist gap retains sender controls'); socket.writes.pop();
    for (const fields of [{connected:false},{connected:true,returnMode:'mirror'},{returnMode:'waiting',playlistPending:false},
        {profile:'audio',mode:'waiting',playlistPending:false},{profile:'audio',mode:'mirror',playlistPending:true}]) {
        socket.emit('data', JSON.stringify({state:fields})+'\n');
        assert.strictEqual(client.musicControl('next'),false,'cached capabilities require an actual controllable media state');
    }
    socket.emit('data', '{"state":{"profile":"video","mode":"hls","phase":"loading","origin":"direct","supportsVideoStop":true,"playlistPending":false}}\n');
    assert.strictEqual(client.state.origin, 'direct');
    assert(client.endVideo());
    assert.deepStrictEqual(socket.writes.pop(), { command: 'end-video' });
    socket.emit('data', '{"state":{"mode":"waiting","phase":"loading"}}\n');
    assert(client.endVideo(), 'early FCUP loading sends the current-video stop command');
    assert.deepStrictEqual(socket.writes.pop(), { command: 'end-video' });
    socket.emit('data', '{"state":{"phase":"waiting"}}\n');
    assert(client.resumeMirror()); assert.deepStrictEqual(socket.writes.pop(), { command: 'resume-mirror' });
    socket.emit('data', '{"state":{"mode":"waiting","playlistPending":true}}\n');
    assert(client.endVideo(), 'the waiting gap between titles can be cancelled');
    socket.writes.pop();
    socket.emit('data', '{"state":{"playlistPending":false,"supportsVideoStop":false}}\n');
    assert.strictEqual(client.endVideo(), false, 'an old runtime cannot get the new signal');
    socket.emit('data', '{"state":{"mode":"audio","phase":"waiting","music":{"epoch":"sender-3","controls":{"next":true}}}}\n');
    assert(client.musicControl('next')); socket.writes.pop();
    socket.emit('data', JSON.stringify({state:{music:{epoch:'sender\n3',controls:{next:true}}}})+'\n');
    assert.strictEqual(client.musicControl('next'),false,'an invalid sender epoch cannot enter the protocol');
    socket.emit('data', '{"state":{"music":{"epoch":"sender-3","controls":{"next":true}}}}\n');
    let acknowledged=false;
    const stopping=client.stop(); stopping.then(()=>{acknowledged=true;});
    assert.strictEqual(client.stop(), stopping, 'concurrent stop calls share one acknowledged request');
    const request=socket.writes.pop(); assert.strictEqual(request.command, 'stop'); assert(/^stop-/.test(request.id));
    assert.strictEqual(client.musicControl('next'),false,'no music command can restart playback while full disconnection is pending');
    await Promise.resolve(); assert.strictEqual(acknowledged, false, 'writing a stop is not its completion');
    socket.emit('data', JSON.stringify({reply:{command:'stop',id:'stale-request',ok:true}})+'\n');
    await Promise.resolve(); assert.strictEqual(acknowledged, false, 'a stale acknowledgment cannot complete the current stop');
    socket.emit('data', JSON.stringify({reply:{command:'stop',id:request.id,ok:true}})+'\n');
    await stopping;
    await client.disconnect();
    assert.strictEqual(socket.writes.length, 0, 'losing the UI does not send an implicit receiver stop');
    assert.strictEqual(socket.ends, 1);
    assert.strictEqual(intervals.size, 0); assert.strictEqual(retries.size, 0);
    assert.strictEqual(client.start('audio'), false);
    const explicit = new BackendClient('/private/control.sock'); explicit.connect();
    const second = sockets[1]; second.connecting = false; second.emit('connect');
    const closing=explicit.destroy();
    assert.strictEqual(second.ends, 0, 'Close keeps the UI socket open until backend cleanup is acknowledged');
    const closeRequest=second.writes[0]; assert.strictEqual(closeRequest.command, 'stop');
    second.emit('data', JSON.stringify({reply:{command:'stop',id:closeRequest.id,ok:true}})+'\n');
    await closing;
    assert.strictEqual(second.ends, 1);
    assert.strictEqual(intervals.size, 0); assert.strictEqual(retries.size, 0);
    const failed = new BackendClient('/private/control.sock'); failed.connect();
    const third=sockets[2]; third.connecting=false; third.emit('connect');
    const failure=failed.destroy().then(()=>{throw Error('failed stop unexpectedly closed the UI');},error=>error);
    const failedRequest=third.writes.pop();
    third.emit('data', JSON.stringify({reply:{command:'stop',id:failedRequest.id,ok:false,error:'receiver_stop_failed'}})+'\n');
    assert.strictEqual((await failure).message, 'receiver_stop_failed');
    assert.strictEqual(third.ends,0, 'a failed disconnect leaves the UI available for retry');
    const timeout=failed.stop().then(()=>{throw Error('unacknowledged stop succeeded');},error=>error);
    const deadline=Array.from(retries).find(fn=>fn.ms===12000); assert(deadline); deadline();
    assert.strictEqual((await timeout).message,'receiver_stop_timeout');
    assert.strictEqual(third.ends,0);
    const lost=failed.stop().then(()=>{throw Error('lost backend stop succeeded');},error=>error);
    third.destroy(); assert.strictEqual((await lost).message,'backend_unavailable');
    await failed.disconnect();
    assert.strictEqual(intervals.size,0); assert.strictEqual(retries.size,0);
    const cached=new BackendClient('/private/control.sock');
    assert.strictEqual(cached.setVideoViewport(1920,720),false,'viewport intent is cached even before a backend socket exists');
    cached.connect(); const fourth=sockets[3];
    assert.strictEqual(cached.start('auto',{width:1920,height:504}),false);
    assert.strictEqual(cached.setVideoViewport(1600,520),false,'the latest canvas wins while connecting');
    fourth.connecting=false; fourth.emit('connect');
    assert.deepStrictEqual(fourth.writes,[{command:'heartbeat'},{command:'video-viewport',width:1600,height:520}]);
    fourth.writes.length=0;
    for(let tick=0;tick<10;tick++) assert(cached.setVideoViewport(1600,520));
    assert.strictEqual(fourth.writes.length,0,'repeated UI ticks deduplicate the same viewport per socket');
    assert(cached.start()); assert.deepStrictEqual(fourth.writes.pop(),{command:'start',profile:'auto',viewport:{width:1600,height:520}});
    assert(cached.setVideoViewport(1600,520));assert.strictEqual(fourth.writes.length,0,'start dimensions also count as sent viewport intent');
    for(const size of [[1921,720],[1920,721],[0,720],[16,14],[2050,720],[2048,2048],['1920',720],[1920,NaN],[Infinity,720]])
        assert.strictEqual(cached.setVideoViewport(size[0],size[1]),false,'invalid viewport cannot enter the protocol');
    assert.strictEqual(cached.start('auto',{width:2048,height:2048}),false);
    assert.strictEqual(fourth.writes.length,0);
    assert(cached.setVideoViewport(1920,720)); assert.deepStrictEqual(fourth.writes.pop(),{command:'video-viewport',width:1920,height:720});
    fourth.destroy();
    assert.strictEqual(cached.state.connected,false,'backend loss cannot leave a connected status behind');
    const reconnect=Array.from(retries).find(fn=>fn.ms===500); assert(reconnect);retries.delete(reconnect);reconnect();
    const fifth=sockets[4];fifth.connecting=false;fifth.emit('connect');
    assert.deepStrictEqual(fifth.writes,[{command:'heartbeat'},{command:'video-viewport',width:1920,height:720}],
        'a fresh socket replays the latest requested canvas instead of stale backend geometry');
    fifth.emit('data','{"state":{"connected":true}}\n');
    fourth.emit('data','{"state":{"connected":false}}\n');
    fourth.emit('close');
    assert.strictEqual(cached.state.connected,true,'data or closure from an old socket cannot overwrite a reconnected session');
    await cached.disconnect();
    assert.strictEqual(intervals.size,0);assert.strictEqual(retries.size,0);
    console.log('Backend client: automatic media, sender capabilities and acknowledged disconnect/failure deadlines passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
