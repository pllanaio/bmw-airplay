'use strict';
const assert = require('assert'), fs = require('fs'), os = require('os'), path = require('path');
const EventEmitter = require('events');
const { Receiver } = require('../apps/pllana_airplay/receiver');
(async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'airplay-receiver-test-'));
    const calls = [];
    const r = new Receiver({ dataDir: dir, audioSink: 'fakesink', skipRuntimeCheck: true, spawn: (bin, args, options) => {
        const child = new EventEmitter(); child.pid = 900000 + calls.length;
        child.stdout = new EventEmitter(); child.stderr = new EventEmitter();
        calls.push({ args, child, options }); return child;
    } });
    r.signal = child => setImmediate(() => child.emit('close', 0));
    try {
        assert(r.start()); assert.strictEqual(r.state.phase, 'waiting', 'works without Node-15 spawn event');
        assert(calls[0].args.includes('-hls'), 'advertise the actual HLS player');
        assert.strictEqual(calls[0].args[calls[0].args.indexOf('-hls') + 1], '2', 'use legacy HLS parser for YouTube codec negotiation');
        assert.strictEqual(calls[0].args[calls[0].args.indexOf('-n') + 1], 'BMW AirPlay by pllana.io');
        assert.strictEqual(calls[0].options.env.MGU_HLS_AUDIO_SINK, 'fakesink');
        assert(!r.start(), 'no overlapping receiver');
        const mac = calls[0].args[calls[0].args.indexOf('-m') + 1];
        const events = [];
        r.on('diagnostic', code => events.push(code));
        calls[0].child.stdout.emit('data', '*** CLIENT MUST NOW ENTER PIN = "1234" AS AIRPLAY PASSWORD\n');
        assert.strictEqual(r.state.pin, '1234', 'screen follows actual native PIN');
        assert(events.every(code => code.indexOf('1234') < 0), 'diagnostics exclude PIN values');
        calls[0].child.stderr.emit('data', 'MGU_CRASH\n/tmp/uxplay(+0xabcd)[0xdeadbeef]\n');
        assert(events.includes('/tmp/uxplay(+0xabcd)[0xdeadbeef]'), 'native backtrace addresses do not contain a mandatory space');
        await r.stop(); assert.strictEqual(r.state.phase, 'stopped');
        assert(r.start());
        assert.strictEqual(calls[1].args[calls[1].args.indexOf('-m') + 1], mac, 'receiver identity survives sessions');
        assert(calls[1].args.includes('-reg'));
        await r.destroy(); assert(!r.start());
        const p = new Receiver(Object.assign({}, r.options, { authentication: 'password' }));
        p.signal = child => setImmediate(() => child.emit('close', 0));
        assert(p.start());
        const passwordArgs = calls[2].args;
        assert(/^[0-9]{6}$/.test(p.state.pin));
        assert.strictEqual(passwordArgs[passwordArgs.indexOf('-pw') + 1], p.state.pin);
        assert(!passwordArgs.includes('-pin'), 'standard password auth is separate from legacy PIN pairing');
        const password = p.state.pin, child = p.child;
        child.stdout.emit('data', 'MGU_MODE hls\n');
        assert.strictEqual(p.state.phase, 'loading');
        assert.strictEqual(p.state.returnMode, 'waiting', 'direct video returns to waiting');
        child.stdout.emit('data', 'MGU_MODE waiting\n');
        assert.strictEqual(p.state.phase, 'waiting');
        child.stdout.emit('data', 'MGU_MODE mirror\nMGU_MODE hls\n');
        assert.strictEqual(p.state.returnMode, 'mirror', 'video entered from mirroring remembers origin');
        p.update({ frame: {sequence: 123} });
        child.stdout.emit('data', 'MGU_MODE hls\n');
        assert.strictEqual(p.state.frame, null, 'new content clears previous frozen frame');
        child.stdout.emit('data', 'MGU_MODE waiting\n');
        assert.strictEqual(p.child, child, 'media mode switches preserve native receiver');
        assert.strictEqual(p.state.pin, password, 'media mode switches preserve password');
        const playlistEvents = [];
        p.on('diagnostic', code => playlistEvents.push(code));
        child.stdout.emit('data', 'MGU_MEDIA_ENDED\nMGU_PLAYLIST_INSERT\nMGU_MEDIA_LOADING\nMGU_MODE hls\n');
        assert.strictEqual(p.child, child, 'the next playlist item keeps the receiver session');
        assert.strictEqual(p.state.pin, password, 'playlist advance needs no new pairing');
        assert.strictEqual(p.state.phase, 'loading');
        assert.strictEqual(p.state.frame, null, 'playlist advance cannot display the previous item as the next video');
        assert(playlistEvents.includes('mgu_media_ended') && playlistEvents.includes('mgu_playlist_insert'));
        // Detached video: only with a runtime that announced the feature.
        const sent = [];
        p.signal = (c, sig) => { if (sig === 'SIGTERM' || sig === 'SIGKILL') setImmediate(() => c.emit('close', 0)); else sent.push(sig); };
        child.stdout.emit('data', 'MGU_MODE mirror\nMGU_MODE hls\n');
        assert.strictEqual(p.detach(), false, 'an old runtime never gets SIGUSR1');
        child.stdout.emit('data', 'MGU_FEATURES detach\n');
        assert.strictEqual(p.detach(), true); assert.deepStrictEqual(sent, ['SIGUSR1']);
        child.stdout.emit('data', 'MGU_MEDIA_DETACHED\n');
        assert.strictEqual(p.state.detached, true);
        p.update({ phase: 'mirroring', frame: { sequence: 123 } });
        child.stdout.emit('data', 'MGU_CONN 0\n');
        assert.strictEqual(p.state.phase, 'mirroring', 'a video keeps playing after all phone sockets close');
        assert(p.state.frame, 'control disconnect cannot hide the detached video');
        assert.strictEqual(p.state.returnMode, 'mirror', 'control disconnect preserves return to mirroring');
        assert.strictEqual(p.detach(), false, 'detach once per video');
        assert.strictEqual(p.resumeMirror(), true); assert.deepStrictEqual(sent, ['SIGUSR1', 'SIGUSR2']);
        child.stdout.emit('data', 'MGU_MODE mirror\n');
        assert.strictEqual(p.state.detached, false, 'back to mirroring clears the detached state');
        child.stdout.emit('data', 'MGU_FEATURES native-detach\nMGU_MODE hls\nMGU_MEDIA_DETACHED\nMGU_MODE waiting\nMGU_MODE hls\n');
        assert.strictEqual(p.features.nativeDetach, true, 'runtime advertises authoritative origin detection');
        assert.strictEqual(p.state.returnMode, 'waiting', 'a later direct video does not inherit stale mirror origin');
        assert.strictEqual(p.state.detached, false, 'later direct video retains normal phone controls');
        child.stdout.emit('data', 'MGU_MEDIA_ENDED\nMGU_MODE waiting\n');
        assert.strictEqual(p.state.playlistPending, true);
        assert.strictEqual(p.resumeMirror(), false, 'legacy runtime cannot cancel a pending playlist transition');
        child.stdout.emit('data', 'MGU_FEATURES playlist\nMGU_MODE mirror\n');
        assert.strictEqual(p.state.playlistPending, true, 'mirror packets between titles must not hide playlist cancellation');
        assert.strictEqual(p.resumeMirror(), true, 'return to mirroring also cancels the gap between titles');
        child.stdout.emit('data', 'MGU_PLAYLIST_CANCELLED\n');
        assert.strictEqual(p.state.playlistPending, false);
        child.stdout.emit('data', 'MGU_MODE waiting\n');
        assert.strictEqual(p.resumeMirror(), false, 'no repeated cancel once the pending transition has ended');
        child.stdout.emit('data', 'MGU_MODE mirror\n');
        child.stdout.emit('data', 'MGU_MEDIA_DETACHED\n');
        assert.strictEqual(p.state.detached, false, 'late detachment acknowledgement cannot relabel mirroring');
        assert.strictEqual(p.endVideo(), false, 'older runtimes never receive the new video-stop signal');
        child.stdout.emit('data', 'MGU_FEATURES media-stop\nMGU_MODE waiting\nMGU_MEDIA_LOADING\n');
        const signalsBeforeLoadingStop = sent.length;
        assert(p.endVideo(), 'early FCUP loading can be stopped before HLS owns the renderer');
        assert.strictEqual(sent[signalsBeforeLoadingStop], 'SIGWINCH');
        assert.strictEqual(p.child, child); assert.strictEqual(p.state.pin, password);
        child.stdout.emit('data', 'MGU_FEATURES video-modes\nMGU_FEATURES media-stop\nMGU_ORIGIN direct\nMGU_MODE hls\n');
        assert.strictEqual(p.state.origin, 'direct');
        assert.strictEqual(p.state.returnMode, 'waiting', 'native direct origin overrides stale mirror packets');
        assert.strictEqual(p.detach(), false, 'origin-aware runtimes do not receive legacy detach signals');
        const beforeEnd = sent.length;
        assert.strictEqual(p.endVideo(), true);
        assert.strictEqual(sent[beforeEnd], 'SIGWINCH');
        assert.strictEqual(p.child, child, 'ending a direct video preserves the paired receiver');
        assert.strictEqual(p.state.pin, password);
        child.stdout.emit('data', 'MGU_PLAYLIST_CANCELLED\nMGU_RETURN waiting\nMGU_MODE waiting\n');
        assert.strictEqual(p.state.returnMode, 'waiting');
        assert.strictEqual(p.state.phase, 'waiting');
        assert.strictEqual(p.state.origin, null);
        assert.strictEqual(p.endVideo(), false, 'no repeated stop when there is no current video or playlist');
        child.stdout.emit('data', 'MGU_ORIGIN mirror\nMGU_MODE hls\nMGU_MEDIA_DETACHED\n');
        assert.strictEqual(p.state.returnMode, 'mirror');
        assert.strictEqual(p.state.origin, 'mirror');
        assert.strictEqual(p.state.detached, false, 'new origin markers do not imply ignoring phone media controls');
        assert(p.endVideo());
        child.stdout.emit('data', 'MGU_PLAYLIST_CANCELLED\nMGU_RETURN mirror\nMGU_MODE waiting\n');
        assert.strictEqual(p.state.returnMode, 'mirror', 'mirror-origin video returns toward the active mirror');
        assert.strictEqual(p.state.frame, null);
        assert.strictEqual(p.child, child);
        child.stdout.emit('data', 'MGU_ORIGIN direct\nMGU_MODE hls\nMGU_MEDIA_ENDED\nMGU_RETURN waiting\nMGU_MODE waiting\n');
        assert.strictEqual(p.state.returnMode, 'waiting', 'direct natural EOS never starts a mirror transition');
        assert.strictEqual(p.state.playlistPending, true);
        assert(p.endVideo(), 'ending during a title transition cancels the playlist without disconnecting');
        child.stdout.emit('data', 'MGU_PLAYLIST_CANCELLED\n');
        assert.strictEqual(p.state.playlistPending, false);
        await p.stop();
        assert.strictEqual(p.state.detached, false);
        assert(p.start({ keepPassword: true }));
        assert.strictEqual(p.state.pin, password, 'automatic recovery keeps the password the iPhone knows');
        assert.strictEqual(calls[calls.length - 1].args[calls[calls.length - 1].args.indexOf('-pw') + 1], password);
        await p.stop();
        assert(p.start()); assert.notStrictEqual(p.state.pin, password, 'a manual connect issues a new password');
        await p.stop();
        let uplink = false;
        p.options.hls = () => uplink;
        assert(p.start());
        assert.strictEqual(p.state.directVideo, false);
        assert(!calls[calls.length - 1].args.includes('-hls'), 'without MGU Internet, YouTube must remain mirrored');
        assert(!calls[calls.length - 1].args.includes('-lang'));
        uplink = true;
        assert.strictEqual(p.start(), false, 'a new uplink must not interrupt an active mirror session');
        assert.strictEqual(p.state.directVideo, false);
        await p.stop();
        assert(p.start());
        assert.strictEqual(p.state.directVideo, true);
        assert(calls[calls.length - 1].args.includes('-hls'), 'reconnecting with an uplink enables direct YouTube video');
        const videoPassword = p.state.pin;
        await p.stop();
        let metadataClosed = 0;
        p.options.metadataFactory = (dataDir, runtime) => {
            assert.strictEqual(dataDir, dir); assert.strictEqual(runtime, p.runtime);
            const directory = path.join(dir, 'private-music-session');
            return { env: () => ({ MGU_MUSIC_DIR:directory,MGU_AUDIO_METADATA_DIR:directory }),
                poll: () => ({ revision:1,title:'Current sender song',artist:'Current sender',album:'Current album',artwork:null }),
                close: () => { metadataClosed++; } };
        };
        assert(p.start({ profile: 'audio', keepPassword: true }));
        const audioCall = calls[calls.length - 1], audioChild = p.child;
        assert.strictEqual(p.state.profile, 'audio');
        assert.strictEqual(p.state.mode, 'audio');
        assert.strictEqual(p.state.directVideo, false);
        assert.strictEqual(p.state.pin, videoPassword, 'switching audio/video capabilities retains the password');
        assert.strictEqual(p.state.file, '', 'audio-only allocates no shared-memory video transport');
        assert.strictEqual(p.poll, null, 'audio-only starts no frame poller');
        assert.strictEqual(audioCall.args[audioCall.args.indexOf('-vs') + 1], '0');
        assert(!audioCall.args.includes('-hls') && !audioCall.args.includes('-lang') && !audioCall.args.includes('-s') && !audioCall.args.includes('-avdec'));
        assert.strictEqual(audioCall.options.env.MGU_AUDIO_ONLY, '1');
        assert.strictEqual(audioCall.options.env.MGU_MUSIC_DIR, p.musicDirectory);
        assert.strictEqual(audioCall.options.env.MGU_AUDIO_METADATA_DIR, p.musicDirectory);
        assert(p.musicDirectory.indexOf(dir) === 0, 'native receives only its own private metadata/control directory');
        p.update({ music:Object.assign({},p.state.music,{epoch:'current-sender',controls:{next:true},playbackState:'playing'}) });
        await new Promise((resolve,reject) => {
            const timeout=setTimeout(() => { p.removeListener('state',changed); reject(Error('metadata poll timeout')); },2000);
            function changed(state) { if (state.music && state.music.title === 'Current sender song') { clearTimeout(timeout);p.removeListener('state',changed);resolve(); } }
            p.on('state',changed);
        });
        assert.strictEqual(p.state.music.artist, 'Current sender');
        assert.strictEqual(p.state.music.epoch, 'current-sender', 'metadata polling preserves the authoritative control epoch');
        assert.strictEqual(p.state.music.controls.next, true, 'metadata polling preserves confirmed control capabilities');
        const audioEvents = []; p.on('media', mode => audioEvents.push(mode));
        audioChild.stdout.emit('data', 'MGU_FEATURES audio-only\nMGU_MODE audio\nMGU_AUDIO_WAITING\n');
        assert.strictEqual(p.features.audioOnly, true);
        assert.strictEqual(p.state.phase, 'waiting');
        audioChild.stdout.emit('data', 'MGU_MODE audio\nMGU_AUDIO_PLAY\n');
        assert.strictEqual(p.state.phase, 'audio');
        assert(audioEvents.includes('audio'), 'actual audio packets request the BMW audio route');
        audioChild.stdout.emit('data', 'MGU_MEDIA_LOADING\nMGU_ORIGIN direct\nMGU_MODE hls\nMGU_RETURN waiting\n');
        assert.strictEqual(p.state.phase, 'audio', 'stray video markers cannot leave the audio-only profile');
        assert.strictEqual(p.state.mode, 'audio');
        assert.strictEqual(p.state.origin, null);
        audioChild.stdout.emit('data', 'MGU_AUDIO_WAITING\n');
        assert.strictEqual(p.state.phase, 'waiting');
        assert.strictEqual(p.child, audioChild, 'audio flush/teardown preserves the advertised receiver');
        assert.strictEqual(p.state.pin, videoPassword);
        assert.strictEqual(p.resumeMirror(), false);
        assert.strictEqual(p.endVideo(), false);
        await p.stop();
        assert.strictEqual(metadataClosed, 1);
        assert.strictEqual(p.musicDirectory, ''); assert.strictEqual(p.musicPoll, null); assert.strictEqual(p.state.music, null);
        assert.strictEqual(p.start({ profile: 'invalid' }), false);
        assert.strictEqual(p.state.error, 'invalid_profile');
        assert(p.start({ profile: 'video', keepPassword: true }));
        assert.strictEqual(p.state.profile, 'video');
        assert.strictEqual(calls[calls.length - 1].options.env.MGU_AUDIO_ONLY, '0');
        assert(p.poll, 'returning to video restores frame polling');
        await p.destroy();
        console.log('Node-8 receiver startup, origin-aware video stop/return, audio-only profile, stable identity and stop lifecycle passed');
    } finally {
        await r.destroy();
        for (const name of fs.readdirSync(dir)) fs.unlinkSync(path.join(dir, name));
        fs.rmdirSync(dir);
    }
})().catch(e => { console.error(e); process.exit(1); });
